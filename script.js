  function setLang(lang){
    document.documentElement.lang = (lang==='en'?'en':'zh-CN');
    document.querySelectorAll('[data-i18n]').forEach(el=>{
      const t = I18N[el.getAttribute('data-i18n')];
      if(t) el.innerHTML = t[lang];
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el=>{
      const t = I18N[el.getAttribute('data-i18n-ph')];
      if(t) el.placeholder = t[lang];
    });
    document.querySelectorAll('#langToggle button').forEach(b=>{
      b.classList.toggle('active', b.dataset.set===lang);
    });
    try{ localStorage.setItem('mb_lang', lang); }catch(e){}
  }

  document.getElementById('langToggle').addEventListener('click', e=>{
    const btn = e.target.closest('button[data-set]');
    if(btn) setLang(btn.dataset.set);
  });

  // hero stats count-up
  (function(){
    const els=document.querySelectorAll('.stat b[data-count]');
    if(!els.length) return;
    const reduced=window.matchMedia&&window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    const io2=new IntersectionObserver(es=>{
      es.forEach(en=>{
        if(!en.isIntersecting) return;
        io2.unobserve(en.target);
        const el=en.target,target=+el.dataset.count,suffix=el.dataset.suffix||'';
        if(reduced){el.textContent=target+suffix;return;}
        const t0=performance.now(),dur=1400;
        (function tick(now){
          const pr=Math.min((now-t0)/dur,1),v=Math.round(target*(1-Math.pow(1-pr,3)));
          el.textContent=v+suffix;
          if(pr<1)requestAnimationFrame(tick);
        })(t0);
      });
    },{threshold:.4});
    els.forEach(el=>io2.observe(el));
  })();

  // nav scrollspy
  (function(){
    const links=[...document.querySelectorAll('.nav-links a')];
    const secs=['#top','#services','#why','#process','#faq'];
    function spy(){
      const y=window.scrollY+130;
      let cur=secs[0];
      secs.forEach(id=>{const el=document.querySelector(id);if(el&&el.offsetTop<=y)cur=id;});
      links.forEach(a=>a.classList.toggle('active',a.getAttribute('href')===cur));
    }
    let tick=false;
    window.addEventListener('scroll',()=>{if(!tick){tick=true;requestAnimationFrame(()=>{spy();tick=false;});}},{passive:true});
    spy();
  })();

